// Generates real ecclesiastical-Latin audio for Jacob's own custom-typed vocab
// words (SoundStudio's "+ Add your own word or phrase", RCA First Form Latin 6)
// — same edge-tts + Whisper-verified pipeline as gen-latin-audio.mjs, just
// sourced from mt_custom_vocab (Supabase) instead of the hardcoded manifest,
// since these words don't exist anywhere in the repo. This has to be a local
// script: edge-tts/whisper are CLI binaries (see scripts/lib/tts-verify.mjs),
// not something Vercel's serverless functions can run, so real verified audio
// for a custom word can only ever be generated by running this on Jacob's own
// Mac and shipping the resulting mp3s — never live in-app.
//
// Usage: node --env-file=.env.local scripts/gen-custom-vocab-audio.mjs [--force]
//   --force  re-synthesize + re-verify every row, not just audio_ready=false ones
//
// After running: commit public/audio/latin/custom/ and deploy. Cards in
// SoundStudio upgrade to the real file automatically on next load (audioReady
// synced from mt_custom_vocab via /api/rca-custom-vocab) — no other change needed.

import { mkdir } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const FORCE = process.argv.includes("--force");

const VOICES = ["it-IT-IsabellaNeural", "it-IT-DiegoNeural", "it-IT-GiuseppeMultilingualNeural"];

async function main() {
  const { createClient } = await import("@supabase/supabase-js");
  const { toEcclesiasticalTtsSpelling } = await import(path.join(ROOT, "src/lib/latin-ecclesiastical-spelling.ts"));
  const { slugify } = await import(path.join(ROOT, "src/lib/audio-slug.ts"));
  const { synthesizeAndVerify } = await import(path.join(ROOT, "scripts/lib/tts-verify.mjs"));

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error("Missing NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY — run with --env-file=.env.local");
    process.exit(1);
  }
  const supabase = createClient(url, key);

  let query = supabase.from("mt_custom_vocab").select("user_email, id, latin");
  if (!FORCE) query = query.eq("audio_ready", false);
  const { data: rows, error } = await query;
  if (error) throw error;
  if (!rows.length) {
    console.log("No pending custom vocab words.");
    return;
  }

  const outDir = path.join(ROOT, "public/audio/latin/custom");
  await mkdir(outDir, { recursive: true });

  let done = 0;
  for (const row of rows) {
    const filename = slugify(row.latin);
    const outPath = path.join(outDir, `${filename}.mp3`);
    const ttsSpelling = toEcclesiasticalTtsSpelling(row.latin);
    const result = await synthesizeAndVerify({
      text: ttsSpelling,
      expectedText: ttsSpelling,
      voices: VOICES,
      language: "Italian",
      outPath,
      threshold: 0.65,
    });
    const tag = result.pass ? "PASS " : "FLAG ";
    console.log(`${tag} ${row.latin} (${ttsSpelling}) -> voice=${result.voice} heard "${result.transcript}" score=${result.score.toFixed(2)}`);

    const { error: updateErr } = await supabase
      .from("mt_custom_vocab")
      .update({ audio_ready: true })
      .eq("user_email", row.user_email)
      .eq("id", row.id);
    if (updateErr) console.error(`Failed to mark ${row.latin} audio_ready:`, updateErr);
    else done++;
  }

  console.log(`\n${done}/${rows.length} words generated.`);
  if (done > 0) console.log(`Commit public/audio/latin/custom/ and deploy — cards upgrade automatically on next load.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
